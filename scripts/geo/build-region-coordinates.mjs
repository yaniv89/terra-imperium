// scripts/geo/build-region-coordinates.mjs
// Generates src/data/regionCoordinates.js: a rough lat/lng centroid (+ a rough size, `extent`) for
// every one of the ~4,482 province-level game regions (src/data/regions.js). The centroid places
// combat effects (GlobeEffectsOverlay) and flies the camera to a region on selection/game start;
// `extent` lets src/utils/regionClickAssist.js's globe click-assist tell a small, easy-to-miss
// region (e.g. Tel Aviv) apart from the much bigger one it sits inside (HaMerkaz) — see that file's
// own header for why a plain "closest centroid" search wasn't enough on its own.
//
// Run with: node scripts/geo/build-region-coordinates.mjs
// Reads only already-committed topology (no network fetch).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { feature } from 'topojson-client';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const geoDir = path.join(__dirname, '../../src/data/geo');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

const subregionsTopo = readJson(path.join(geoDir, 'subregions.topo.json'));
const objectKey = Object.keys(subregionsTopo.objects)[0];
const subregionFeatures = feature(subregionsTopo, subregionsTopo.objects[objectKey]).features;

// Crude but sufficient centroid — averaging exterior-ring vertices, not a true area centroid.
// Good enough for camera framing and effect placement, which don't need geographic precision.
// `extent` (also crude: max centroid-to-vertex distance, in degrees, over that same ring) is a
// cheap, comparable-across-regions proxy for "how big is this on screen" without computing a real
// polygon area — precise enough to tell a city-district-sized region from the province around it.
const centroidAndExtentOf = (f) => {
  const polygons = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
  // Use the largest ring (by vertex count) as a rough proxy for the largest landmass, so an
  // archipelago province's centroid lands on its main island rather than averaged out to sea.
  const rings = polygons.map(p => p[0]);
  const largest = rings.reduce((a, b) => (b.length > a.length ? b : a), rings[0]);
  const lng = largest.reduce((s, p) => s + p[0], 0) / largest.length;
  const lat = largest.reduce((s, p) => s + p[1], 0) / largest.length;
  const extent = largest.reduce((max, p) => Math.max(max, Math.hypot(p[0] - lng, p[1] - lat)), 0);
  return { lat, lng, extent };
};

const coordinates = {};
subregionFeatures.forEach((f) => {
  coordinates[f.id] = centroidAndExtentOf(f);
});

const output = `// src/data/regionCoordinates.js
// Real-world lat/lng centroid (+ a rough on-screen size, \`extent\`) for each of the ~4,482
// province-level game regions (src/data/regions.js) — generated by
// scripts/geo/build-region-coordinates.mjs. The centroid places combat effects
// (GlobeEffectsOverlay) and flies the camera to a region on selection/game start; \`extent\` feeds
// the globe's click-assist (src/utils/regionClickAssist.js).
export const REGION_COORDINATES = ${JSON.stringify(coordinates, null, 2)};
`;

writeFileSync(path.join(__dirname, '../../src/data/regionCoordinates.js'), output);
console.log(`Wrote regionCoordinates.js: ${Object.keys(coordinates).length} province centroids.`);
