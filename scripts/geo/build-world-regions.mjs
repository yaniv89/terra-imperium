// scripts/geo/build-world-regions.mjs
// Generates src/data/geo/worldRegions.json: a nation record + real adjacency for every one of the
// 240 countries on Earth. Every nation is symmetric — one whole-country region each, built from
// real population/GDP and real geographic adjacency — which is what lets the player start as any
// of them (src/data/regions.js) rather than one hand-tuned country.
//
// Run with: node scripts/geo/build-world-regions.mjs
// Reads only already-committed data (no network fetch). Adjacency is derived the same principled
// way Phase 11 first computed it: two countries border each other iff any of their real admin-1
// provinces share a TopoJSON arc (subregions-adjacency.json), collapsed here from the
// province-level graph down to the country each province belongs to.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const geoDir = path.join(__dirname, '../../src/data/geo');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

const countriesMeta = readJson(path.join(geoDir, 'countries-meta.json'));
const subregionsMeta = readJson(path.join(geoDir, 'subregions-meta.json'));
const subregionsAdjacency = readJson(path.join(geoDir, 'subregions-adjacency.json'));
// Generated by build-sea-lanes.mjs — run that first. Falls back to "not coastal" for any country
// it hasn't run for yet, rather than failing this build outright.
let coastalFlags = {};
try {
  coastalFlags = readJson(path.join(geoDir, 'coastal.json'));
} catch (e) {
  console.warn('coastal.json not found — run build-sea-lanes.mjs first. Defaulting isCoastal to false for every nation.');
}

const countryOf = (subregionId) => subregionsMeta[subregionId]?.countryId;

// Collapse the province-level border graph into a country-level border graph.
const countryAdjacency = {};
const addEdge = (a, b) => {
  if (!a || !b || a === b) return;
  if (!countryAdjacency[a]) countryAdjacency[a] = new Set();
  countryAdjacency[a].add(b);
};
Object.entries(subregionsAdjacency).forEach(([subId, neighborSubIds]) => {
  const mine = countryOf(subId);
  neighborSubIds.forEach((nSubId) => addEdge(mine, countryOf(nSubId)));
});

// A rough 0-10 development index from GDP-per-capita, used to seed infrastructure/strategicValue —
// richer nations score modestly higher, but this is flavor, not balance; every nation starts on
// equal footing (100% control of its own territory).
const developmentIndex = (population, gdpMillions) => {
  const gdpPerCapita = (gdpMillions * 1e6) / Math.max(population, 1);
  return Math.min(10, Math.max(1, Math.round(Math.log10(Math.max(gdpPerCapita, 100)) * 2.2)));
};

// Real GDP/population span many orders of magnitude (a $21T economy vs. a $1B one) — used
// linearly, per-turn gold income would range from single digits to hundreds of thousands, making
// the starting treasury (a few hundred gold) meaningless within one turn for a superpower. Log-
// scaling compresses that into a playable band, the same trick militaryFromPopulation already
// uses below for the same reason.
const goldFromGdp = (gdpMillions) => Math.round(40 * Math.log10(Math.max(gdpMillions, 1)));
const hrFromPopulation = (population) => Math.round(25 * Math.log10(Math.max(population, 1)));

const worldRegions = {};
Object.entries(countriesMeta).forEach(([countryId, meta]) => {
  const dev = developmentIndex(meta.population, meta.gdpMillions);
  const neighbors = Array.from(countryAdjacency[countryId] || []);

  worldRegions[countryId] = {
    id: countryId,
    name: meta.name,
    type: 'nation',
    startOwner: countryId,
    startControl: 100,
    population: meta.population,
    infrastructure: dev,
    strategicValue: dev,
    terrain: 'mixed',
    resources: {
      gold: goldFromGdp(meta.gdpMillions),
      hr: hrFromPopulation(meta.population)
    },
    fortification: 1,
    isCapital: true, // this single region IS this nation's whole territory — its own anchor
    isCoastal: !!coastalFlags[countryId],
    neighbors,
    description: meta.name
  };
});

writeFileSync(path.join(geoDir, 'worldRegions.json'), JSON.stringify(worldRegions));
console.log(`Wrote worldRegions.json: ${Object.keys(worldRegions).length} nations, ${Object.values(worldRegions).reduce((s, r) => s + r.neighbors.length, 0)} directed border edges.`);
