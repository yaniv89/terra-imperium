// scripts/icons/generate-icon-data.mjs
// One-time (re-runnable) generator: pulls real, hand-drawn silhouette paths from game-icons.net
// (via the @iconify-json/game-icons npm package — installed as a devDependency purely so this
// script can read its icons.json; the game itself never imports the package at runtime, only the
// static path strings this script writes into src/data/unitIcons.js / buildingIcons.js) and
// replaces the previous procedurally-hand-coded geometric placeholders with real icon art.
//
// Why this instead of an AI image generator or a user-supplied reference photo: game-icons.net is
// a library of 4,000+ CC-BY 3.0 icons purpose-drawn for exactly this (military units, buildings,
// resources), so it's free, genuinely well-drawn, legally clear with attribution, and fully
// scriptable — no manual asset sourcing needed for the ~65 icons this game uses.
//
// Run with: node scripts/icons/generate-icon-data.mjs
//
// Attribution (CC-BY 3.0 requires it): icons courtesy of game-icons.net contributors —
// see https://game-icons.net for individual artist credit; kept alongside the generated files below.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import gameIcons from '@iconify-json/game-icons/icons.json' with { type: 'json' };

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.join(__dirname, '..', '..', 'src', 'data');

// game-icons.net icons are all on a 512x512 viewBox (see GlobeEffectsOverlay.jsx's
// ICON_CONTENT_TRANSFORM, sized to match: scale(0.24 / 5.12) translate(-256,-256)).
const getPath = (iconName) => {
  const body = gameIcons.icons[iconName]?.body;
  if (!body) throw new Error(`Unknown game-icons.net icon: ${iconName}`);
  const match = body.match(/\sd="([^"]+)"/);
  if (!match) throw new Error(`No path data found for icon: ${iconName}`);
  return match[1];
};

const UNIT_ICONS = {
  bronze: { infantry: 'stone-spear', cavalry: 'chariot', ranged: 'sling', siege: 'siege-ram', naval: 'galley' },
  classical: { infantry: 'gladius', cavalry: 'elephant', ranged: 'bowman', siege: 'catapult', naval: 'trireme' },
  kingdoms: { infantry: 'pikeman', cavalry: 'mounted-knight', ranged: 'crossbow', siege: 'trebuchet', naval: 'drakkar' },
  gunpowder: { infantry: 'musket', cavalry: 'saber-and-pistol', ranged: 'crossed-pistols', siege: 'cannon', naval: 'galleon' },
  modern: { infantry: 'rifle', cavalry: 'battle-tank', ranged: 'machine-gun', siege: 'artillery-shell', naval: 'battleship', air: 'jet-fighter' }
};

const BUILDING_ICONS = {
  food: { bronze: 'wheat', classical: 'aqueduct', kingdoms: 'windmill', gunpowder: 'granary', modern: 'farm-tractor' },
  economy: { classical: 'trade', kingdoms: 'coins-pile', gunpowder: 'bank', modern: 'banknote' },
  military: { bronze: 'battle-axe', classical: 'spartan-helmet', gunpowder: 'crossed-sabres', modern: 'brodie-helmet' },
  defense: { bronze: 'stone-wall', classical: 'roman-shield', gunpowder: 'defensive-wall', modern: 'bunker' },
  science: { classical: 'scroll-unfurled', kingdoms: 'open-book', gunpowder: 'bubbling-flask', modern: 'observatory' },
  industry: { classical: 'anvil', gunpowder: 'factory', modern: 'factory-arm' },
  culture: { bronze: 'egyptian-temple', classical: 'greek-temple', kingdoms: 'saint-basil-cathedral', modern: 'theater-curtains' },
  naval: { classical: 'wooden-pier', kingdoms: 'harbor-dock', gunpowder: 'anchor', modern: 'cargo-ship' },
  logistics: { bronze: 'old-wagon', kingdoms: 'mine-wagon', modern: 'forklift' }
};

const EXTRACTION_ICONS = { copper: 'ore', iron: 'minerals', oil: 'oil-rig' };

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const unitIconsSource = `// src/data/unitIcons.js
// AUTO-GENERATED by scripts/icons/generate-icon-data.mjs — do not hand-edit; change the icon-name
// mapping in that script and re-run it instead.
//
// Real per-(age x class) unit silhouettes, sourced from game-icons.net (CC-BY 3.0 — see
// https://game-icons.net and the per-icon credits in that script) rather than AI-generated or
// hand-coded geometric art. Each path is a single monochrome silhouette on a 0..512 viewBox
// (game-icons.net's native size), meant to be recolored via fill="currentColor" at render time and
// rescaled into the effect overlay's local glyph space (see GlobeEffectsOverlay.jsx's
// ICON_CONTENT_TRANSFORM). Keyed by ageId then classId, matching src/data/unitClasses.js's
// UNIT_ROSTER shape exactly — 'air' only exists from 'modern'.
export const UNIT_ICON_PATHS = {
${Object.entries(UNIT_ICONS).map(([ageId, classes]) => `  ${ageId}: {
${Object.entries(classes).map(([classId, iconName]) => `    ${classId}: ${quote(getPath(iconName))} /* game-icons.net: ${iconName} */`).join(',\n')}
  }`).join(',\n')}
};

export const getUnitIconPath = (ageId, classId) => UNIT_ICON_PATHS[ageId]?.[classId] || null;
`;

const buildingIconsSource = `// src/data/buildingIcons.js
// AUTO-GENERATED by scripts/icons/generate-icon-data.mjs — do not hand-edit; change the icon-name
// mapping in that script and re-run it instead.
//
// Real per-(category x age-tier) building silhouettes, plus one per resource-extraction building,
// sourced from game-icons.net (CC-BY 3.0 — see https://game-icons.net and the per-icon credits in
// that script). Same convention as unitIcons.js: single monochrome path, 0..512 viewBox, rescaled
// into the effect overlay's local glyph space at render time. Keyed exactly like
// src/data/buildings.js's BUILDING_CATEGORIES tiers (a category only has an entry for the ages it
// actually has a tier in — a missing age here means that category has no new tier that age, same
// as the building data itself) and src/data/buildings.js's EXTRACTION_BUILDINGS.
export const BUILDING_ICON_PATHS = {
${Object.entries(BUILDING_ICONS).map(([categoryId, ages]) => `  ${categoryId}: {
${Object.entries(ages).map(([ageId, iconName]) => `    ${ageId}: ${quote(getPath(iconName))} /* game-icons.net: ${iconName} */`).join(',\n')}
  }`).join(',\n')}
};

// Resource extraction buildings — one fixed age per resource (see src/data/buildings.js's
// EXTRACTION_BUILDINGS: copper=bronze, iron=kingdoms, oil=modern), so no age dimension here.
export const EXTRACTION_ICON_PATHS = {
${Object.entries(EXTRACTION_ICONS).map(([resourceId, iconName]) => `  ${resourceId}: ${quote(getPath(iconName))} /* game-icons.net: ${iconName} */`).join(',\n')}
};

export const getBuildingIconPath = (categoryId, ageId) => BUILDING_ICON_PATHS[categoryId]?.[ageId] || null;
export const getExtractionIconPath = (resourceId) => EXTRACTION_ICON_PATHS[resourceId] || null;
`;

writeFileSync(path.join(dataDir, 'unitIcons.js'), unitIconsSource);
writeFileSync(path.join(dataDir, 'buildingIcons.js'), buildingIconsSource);
console.log('Wrote src/data/unitIcons.js and src/data/buildingIcons.js from game-icons.net data.');
