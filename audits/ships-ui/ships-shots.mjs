// Fleet in port: the army sheet opens on it, boards troops, unloads. Dev server: npx vite --port 5399
//   node audits/ships-ui/ships-shots.mjs [phone|desktop]
import { launchBrowser } from '../../scripts/lib/browserLaunch.mjs';
import fs from 'node:fs';
const mode = process.argv[2] || 'phone';
const URL_BASE = 'http://localhost:5399/terra-imperium/';
const CHROME = ['C:/Program Files/Google/Chrome/Application/chrome.exe'].find((p) => fs.existsSync(p));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const click = (l) => l.dispatchEvent('click');
const phone = mode === 'phone';
const browser = await launchBrowser({ executablePath: CHROME, headless: true });
const ctx = await browser.newContext({ viewport: phone ? { width: 844, height: 390 } : { width: 1366, height: 800 }, isMobile: phone, hasTouch: phone, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(URL_BASE); await page.evaluate(() => localStorage.clear()); await page.goto(URL_BASE);
await page.locator('[data-people]').first().waitFor({ timeout: 120000 });
await page.fill('input[aria-label="Search peoples"]', 'Ahhiyawa');
await click(page.locator('[data-people]').first());
await page.getByTestId('start-step-ready').dispatchEvent('click');
await click(page.getByRole('button', { name: /^Begin as/ }));
const skip = page.getByRole('button', { name: 'Skip' });
await skip.waitFor({ state: 'visible', timeout: 30000 }).catch(() => {});
if (await skip.isVisible().catch(() => false)) await click(skip);
await page.getByTestId('world-top-bar').waitFor({ timeout: 60000 });
await wait(2500);
const research = page.getByTestId('research-let-advisor');
if (await research.isVisible().catch(() => false)) await click(research);
const tile = await page.evaluate(async () => {
  const s = window.__game.state; const me = s.playerNationId; const cap = s.regions[s.nations[me].capitalRegionId];
  const base = { ownerId: me, regionId: cap.id, homeRegionId: cap.id, tile: cap.tile, strength: 100, maxStrength: 100, morale: 100, movesLeft: 2, xp: 0, promotions: [], embarkedOn: null };
  const units = { ...s.units, fleet1: { ...base, id: 'fleet1', domain: 'naval', classId: 'naval', navalLine: 'warship', transportCapacity: 2 }, inf1: { ...base, id: 'inf1', domain: 'land', classId: 'infantry' } };
  window.__game.dispatch({ type: 'LOAD_GAME', payload: { ...s, units } });
  const m = await import('/terra-imperium/src/components/map/marchEvents.js');
  window.__m = m; return cap.tile;
});
await wait(500);
const shot = async (n) => { await wait(600); await page.screenshot({ path: `audits/ships-ui/${n}-${mode}.png` }); };
const open = () => page.evaluate((t) => window.__m.selectArmy(t), tile);
await open(); await wait(600);
console.log('sheet', await page.getByTestId('army-sheet').isVisible(), 'switch', await page.getByTestId('army-switch').isVisible());
await click(page.getByTestId('army-switch')); await wait(400);
await shot('1-fleet-in-port');
console.log('board button', await page.getByTestId('board-ship').count());
await click(page.getByTestId('board-ship').first()); await wait(500);
await shot('2-boarded');
console.log('unload button', await page.getByTestId('unload-ship').count(), 'embarked', await page.evaluate(() => Object.values(window.__game.state.units).filter((u) => u.embarkedOn).length));
await click(page.getByTestId('unload-ship').first()); await wait(500);
console.log('after unload', await page.evaluate(() => Object.values(window.__game.state.units).filter((u) => u.embarkedOn).length));
console.log('errors', errors.length, errors.slice(0, 2));
await browser.close();
